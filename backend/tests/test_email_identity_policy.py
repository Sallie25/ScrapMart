@pytest.mark.parametrize("local", ["person", "Σ"])
def test_failed_required_domain_projection_is_not_silently_discarded(local):
    # This source domain is valid IDNA, but its casefold becomes a 64-character
    # ASCII label. The canonical alias alone must not be returned as success.
    result = policy.legacy_email_identity(local + "@" + "ß" * 32 + ".test")
    assert result.classification is policy.LegacyClassification.UNCLASSIFIABLE
    assert result.blocks_readiness and result.aliases == ()
    assert result.reason == "alias_transformation_failed"


def test_alias_key_failure_cannot_return_partial_results(monkeypatch):
    original = policy._check_key

    def fail_compatibility(key):
        if key == "person@fass.test":
            raise ValueError("must not appear in results")
        return original(key)

    monkeypatch.setattr(policy, "_check_key", fail_compatibility)
    result = policy.legacy_email_identity("person@faß.test")
    assert result.classification is policy.LegacyClassification.UNCLASSIFIABLE
    assert result.aliases == () and result.blocks_readiness
    assert "must not appear" not in repr(result)


