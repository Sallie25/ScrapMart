def test_ascii_exact_candidates_are_not_blocked_by_duplicate_transforms():
    result = policy.legacy_email_identity("I+Tag.Name@EXAMPLE.TEST")
    assert pairs(result) == (("i+tag.name@example.test", "owned"),)
    # Different local spellings keep their dots/tags; there is no provider rule.
    keys = {policy.canonical_registration_key(value) for value in [
        "first.last@example.test", "firstlast@example.test", "first.last+tag@example.test",
    ]}
    assert len(keys) == 3


def test_every_generated_key_obeys_committed_reservation_constraints():
    for source, _ in GOLDEN_ALIASES:
        aliases = policy.legacy_email_identity(source).aliases
        assert len(aliases) <= 9
        keys = tuple(alias.key for alias in aliases)
        assert keys == tuple(sorted(set(keys)))
        for key in keys:
            assert key.isascii() and 3 <= len(key) <= 255
            assert all(33 <= ord(char) <= 126 for char in key)
            assert key == key.lower() and key.count("@") == 1
            assert not key.startswith("@") and not key.endswith("@")
            assert policy.canonical_registration_key(key) == key


def test_long_valid_key_and_overlong_key():
    key = "a" * 64 + "@" + "b" * 63 + "." + "c" * 63 + "." + "d" * 61
    assert len(key) == 254
    assert policy.canonical_registration_key(key) == key
    with pytest.raises(policy.InvalidRegistrationEmail):
        policy.canonical_registration_key(key + "dd")


def test_versions_and_golden_fingerprint_do_not_depend_on_python_patch(monkeypatch):
    assert policy.normalization_versions() == policy.NormalizationVersions("15.1.0", "2.3.0", "3.20", "18.0.0", "18.0.0")
    assert policy.policy_fingerprint() == "cbdc5198ab2b1c3f23062e5318c97f0ab4e403023a69035e355bc8e8c431e59f"
    fingerprint = policy.policy_fingerprint()
    monkeypatch.setattr(sys, "version_info", (sys.version_info.major, sys.version_info.minor, 999, "final", 0))
    monkeypatch.setattr(sys, "version", "3.13.999")
    assert policy.policy_fingerprint() == fingerprint


